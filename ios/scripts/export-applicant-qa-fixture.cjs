const doc = new JSDOM(html).window.document;
if (!doc.querySelector('form#personalInformation[action="enterPersonalInfo"][method="post"]') ||
    doc.querySelectorAll('input,select,textarea').length !== 29) throw new Error('Review changed Iowa applicant schema.');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== html) throw new Error('Regenerate the iPhone QA fixture.');
} else {
  fs.mkdirSync(path.dirname(output), {recursive:true});
  fs.writeFileSync(output, html);
}
