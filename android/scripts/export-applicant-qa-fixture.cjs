#!/usr/bin/env node
'use strict';

// Run from any directory; --check verifies that the committed Android test asset
// still matches the shared reconstructed schema. No live page is downloaded.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { JSDOM } = require('jsdom');
const source = path.resolve(__dirname, '../../tests/fixtures/iowa-personal-information.cjs');
const output = path.resolve(__dirname, '../app/src/androidTest/assets/iowa-personal-information.html');
const fixture = require(source);
const digest = crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
const html = `<!doctype html>
<!-- GENERATED by android/scripts/export-applicant-qa-fixture.cjs.
Source: tests/fixtures/iowa-personal-information.cjs (reconstructed public metadata, not a live capture).
Source SHA-256: ${digest}
Fictional, intercepted Android QA only. No session material or network-capable submit handler. -->
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; form-action 'none'; base-uri 'none'">
<title>Local reconstructed Iowa applicant fixture</title>
<style>body{font:16px sans-serif;margin:0;padding:16px;color:#16352a;background:white}label,input,select,button{display:block;margin:8px 0}input,select{box-sizing:border-box;max-width:100%;min-height:32px}button{min-height:40px}fieldset{min-width:0;margin:16px 0}legend{max-width:100%;overflow-wrap:anywhere}</style>
</head><body><p>LOCAL SYNTHETIC QA — NO DATA IS SENT</p><main>${fixture.html}</main>
<script>
(${fixture.attachConditionalHandlers.toString()})(document);
window.__qaContinueClicks = 0;
document.querySelector('.saveAndContinueButton').addEventListener('click', () => { window.__qaContinueClicks++; });
</script></body></html>
`;
// Validate that generation preserves the observed form and all controls.
const document = new JSDOM(html).window.document;
if (!document.querySelector('form#personalInformation[action="enterPersonalInfo"][method="post"]') ||
    document.querySelectorAll('input,select,textarea').length !== 29) throw new Error('Applicant fixture schema changed; review before exporting.');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== html) throw new Error('Regenerate the Android applicant QA asset.');
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, html);
}
